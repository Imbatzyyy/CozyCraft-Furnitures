-- Storefront experience controls with deliberately narrow reads and writes.
-- Product comparison and fit checking stay client-side; only durable customer
-- intent and administrator-managed configuration live in Postgres.

create table public.delivery_service_areas (
  id bigint generated by default as identity primary key,
  area_code text not null,
  name text not null,
  description text not null default '',
  delivery_fee numeric(12,2) not null default 0 check (delivery_fee >= 0),
  free_delivery_minimum numeric(12,2) check (free_delivery_minimum is null or free_delivery_minimum >= 0),
  lead_time_min_days integer not null default 2 check (lead_time_min_days between 0 and 60),
  lead_time_max_days integer not null default 5 check (lead_time_max_days between lead_time_min_days and 90),
  assembly_available boolean not null default false,
  active boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index delivery_service_areas_area_code_unique
  on public.delivery_service_areas (lower(area_code));
create index delivery_service_areas_public_lookup_idx
  on public.delivery_service_areas (active, sort_order, id)
  include (area_code, name, delivery_fee, free_delivery_minimum, lead_time_min_days, lead_time_max_days, assembly_available);

create table public.product_alerts (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  product_id text not null references public.products(id) on delete cascade,
  alert_type text not null check (alert_type in ('back_in_stock', 'price_drop')),
  target_price numeric(12,2) check (target_price is null or target_price >= 0),
  active boolean not null default true,
  last_triggered_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, product_id, alert_type)
);

create index product_alerts_active_product_idx
  on public.product_alerts (product_id, alert_type)
  include (user_id, target_price, created_at)
  where active;
create index product_alerts_user_idx
  on public.product_alerts (user_id, active, created_at desc);

create table public.search_synonyms (
  id bigint generated by default as identity primary key,
  term text not null,
  synonyms text[] not null default '{}',
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (char_length(trim(term)) between 2 and 80),
  check (cardinality(synonyms) <= 20)
);

create unique index search_synonyms_term_unique
  on public.search_synonyms (lower(term));
create index search_synonyms_public_lookup_idx
  on public.search_synonyms (active, lower(term)) include (synonyms);

create table public.search_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  query text not null,
  normalized_query text not null,
  result_count integer not null check (result_count >= 0),
  collection text,
  created_at timestamptz not null default now(),
  check (char_length(query) between 2 and 120),
  check (char_length(normalized_query) between 2 and 120)
);

create index search_events_admin_recent_idx
  on public.search_events (created_at desc)
  include (normalized_query, result_count, collection);
create index search_events_user_dedupe_idx
  on public.search_events (user_id, normalized_query, created_at desc);

