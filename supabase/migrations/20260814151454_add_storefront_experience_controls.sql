create or replace function public.record_catalog_search(
  p_query text,
  p_result_count integer,
  p_collection text default null
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_query text := left(trim(coalesce(p_query, '')), 120);
  v_normalized text;
begin
  if v_user_id is null or char_length(v_query) < 2 then
    return;
  end if;
  v_normalized := lower(regexp_replace(v_query, '\s+', ' ', 'g'));
  if exists (
    select 1
    from public.search_events
    where user_id = v_user_id
      and normalized_query = v_normalized
      and created_at > now() - interval '15 minutes'
  ) then
    return;
  end if;
  insert into public.search_events (user_id, query, normalized_query, result_count, collection)
  values (v_user_id, v_query, v_normalized, greatest(coalesce(p_result_count, 0), 0), left(nullif(trim(p_collection), ''), 80));
end;
$$;

revoke all on function public.record_catalog_search(text, integer, text) from public, anon;
grant execute on function public.record_catalog_search(text, integer, text) to authenticated;

